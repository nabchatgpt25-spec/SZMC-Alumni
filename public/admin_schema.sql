-- 1. Create Enums if not existing
DO $$ BEGIN
  CREATE TYPE public.user_role AS ENUM ('member', 'batch_representative', 'moderator', 'admin');
EXCEPTION
  WHEN duplicate_object THEN NULL;
END $$;

DO $$ BEGIN
  CREATE TYPE public.verification_doc_type AS ENUM ('id_card', 'nid_card', 'hsc_slip', 'souvenir');
EXCEPTION
  WHEN duplicate_object THEN NULL;
END $$;

DO $$ BEGIN
  CREATE TYPE public.request_review_status AS ENUM ('pending', 'approved', 'rejected');
EXCEPTION
  WHEN duplicate_object THEN NULL;
END $$;

-- 2. Document Submissions Table
CREATE TABLE IF NOT EXISTS public.admin_doc_submissions (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id BIGINT NOT NULL REFERENCES public.alumni_profiles(id) ON DELETE CASCADE,
  batch_year SMALLINT NOT NULL,
  college_roll VARCHAR(32) NOT NULL,
  academic_stream VARCHAR(32) NOT NULL DEFAULT 'Science',
  academic_group VARCHAR(32) NULL,
  doc_type public.verification_doc_type NOT NULL DEFAULT 'id_card',
  doc_type_label VARCHAR(128) NOT NULL DEFAULT 'Student ID Card',
  storage_object_path TEXT NOT NULL CHECK (char_length(trim(storage_object_path)) > 0),
  status public.request_review_status NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'approved', 'rejected')),
  reviewed_by BIGINT NULL REFERENCES public.alumni_profiles(id) ON DELETE SET NULL,
  reviewed_at TIMESTAMPTZ NULL,
  admin_note TEXT NULL,
  submitted_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT chk_admin_doc_no_self_review CHECK (reviewed_by IS NULL OR reviewed_by <> user_id)
);

CREATE INDEX IF NOT EXISTS idx_admin_doc_status_submitted
  ON public.admin_doc_submissions (status, submitted_at DESC);
CREATE INDEX IF NOT EXISTS idx_admin_doc_user_id
  ON public.admin_doc_submissions (user_id, submitted_at DESC);

-- 3. System Audit Logs (Append-Only)
CREATE TABLE IF NOT EXISTS public.audit_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_profile_id BIGINT NULL REFERENCES public.alumni_profiles(id) ON DELETE SET NULL,
  actor_auth_id UUID NULL REFERENCES auth.users(id) ON DELETE SET NULL,
  actor_role public.user_role NULL,
  action VARCHAR(120) NOT NULL,
  entity_table VARCHAR(64) NOT NULL,
  entity_id TEXT NOT NULL,
  old_values JSONB NULL,
  new_values JSONB NULL,
  reason TEXT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_audit_logs_actor
  ON public.audit_logs (actor_profile_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_audit_logs_table_action
  ON public.audit_logs (entity_table, action, created_at DESC);

-- 4. Helper Security Functions
CREATE OR REPLACE FUNCTION public.is_admin()
RETURNS BOOLEAN
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public, extensions
AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.alumni_profiles
    WHERE auth_user_id = auth.uid() AND role = 'admin'
  );
$$;

CREATE OR REPLACE FUNCTION public.is_admin_or_mod()
RETURNS BOOLEAN
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public, extensions
AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.alumni_profiles
    WHERE auth_user_id = auth.uid() AND role IN ('admin', 'moderator')
  );
$$;

GRANT EXECUTE ON FUNCTION public.is_admin() TO anon, authenticated, service_role;
GRANT EXECUTE ON FUNCTION public.is_admin_or_mod() TO anon, authenticated, service_role;

-- 5. Trigger: Auto-Verify Alumnus When ID Document is Approved
CREATE OR REPLACE FUNCTION public.handle_admin_doc_submission_review()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, extensions
AS $$
BEGIN
  IF NEW.status = 'approved' AND (OLD.status IS DISTINCT FROM 'approved') THEN
    -- Update applicant profile
    UPDATE public.alumni_profiles
    SET
      verification_status = 'verified',
      verification_method = 'document_review',
      verified_at = COALESCE(NEW.reviewed_at, now()),
      verified_by_profile_id = NEW.reviewed_by,
      updated_at = now()
    WHERE id = NEW.user_id;

    -- Audit log
    INSERT INTO public.audit_logs (
      actor_profile_id,
      action,
      entity_table,
      entity_id,
      new_values,
      reason
    ) VALUES (
      NEW.reviewed_by,
      'APPROVE_VERIFICATION_DOC',
      'admin_doc_submissions',
      NEW.id::TEXT,
      jsonb_build_object('user_id', NEW.user_id, 'doc_type', NEW.doc_type),
      COALESCE(NEW.admin_note, 'Approved by admin review')
    );
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_handle_admin_doc_submission_review ON public.admin_doc_submissions;
CREATE TRIGGER trg_handle_admin_doc_submission_review
AFTER UPDATE ON public.admin_doc_submissions
FOR EACH ROW
EXECUTE FUNCTION public.handle_admin_doc_submission_review();
