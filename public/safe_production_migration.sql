-- 9. STORAGE BUCKET ACCESS (Gallery, Avatars, Posts)
-- ==============================================================================

DO $$
BEGIN
  INSERT INTO storage.buckets (id, name, public)
  VALUES
    ('gallery', 'gallery', true),
    ('avatars', 'avatars', true),
    ('posts', 'posts', true)
  ON CONFLICT (id) DO UPDATE SET public = true;

  DROP POLICY IF EXISTS "public_read_gallery" ON storage.objects;
  CREATE POLICY "public_read_gallery" ON storage.objects FOR SELECT USING (bucket_id IN ('gallery', 'avatars', 'posts'));

  DROP POLICY IF EXISTS "public_insert_gallery" ON storage.objects;
  CREATE POLICY "public_insert_gallery" ON storage.objects FOR INSERT WITH CHECK (bucket_id IN ('gallery', 'avatars', 'posts'));

  DROP POLICY IF EXISTS "public_update_gallery" ON storage.objects;
  CREATE POLICY "public_update_gallery" ON storage.objects FOR UPDATE USING (bucket_id IN ('gallery', 'avatars', 'posts'));
EXCEPTION WHEN OTHERS THEN
  NULL;
END $$;
