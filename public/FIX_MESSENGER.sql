-- 8. IMMUTABILITY TRIGGER: PREVENT USERS FROM CHANGING THEIR OWN ROLE
-- -----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.guard_profile_role_security()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  -- If role is being changed, ensure caller is an established super_admin
  IF NEW.role IS DISTINCT FROM OLD.role THEN
    IF NOT public.is_current_user_super_admin() THEN
      RAISE EXCEPTION 'Access Denied: Alumni cannot modify or elevate their own role.';
    END IF;
  END IF;
  NEW.updated_at = now();
  RETURN NEW;
END;
$$;

