// =============================================================================
// BUILD: supabase/APPLY_ALL.sql  (+ the legacy full-schema download files)
//
// The previous scripts/generate_master_sql.js kept a hand-maintained copy of
// the SQL that had drifted away from supabase/migrations/*.sql (missing
// functions, wrong notification columns, enum values that do not exist...),
// which produced a schema that could not be installed.
//
// This script builds the single "run everything" file directly from the
// migration files, in order, so the bundle can never drift again.
//
// Usage: node scripts/build_apply_all.js
// =============================================================================

import fs from 'fs';
import path from 'path';

const migrationsDir = path.resolve('supabase', 'migrations');

const files = fs
  .readdirSync(migrationsDir)
  .filter((f) => f.endsWith('.sql'))
  .sort((a, b) => a.localeCompare(b, 'en', { numeric: true }));

if (files.length === 0) {
  console.error('No migrations found in', migrationsDir);
  process.exit(1);
}

const header = `-- =============================================================================
-- SHAHEED ZIAUR RAHMAN MEDICAL COLLEGE (SZMC BOGURA) ALUMNI NETWORK
-- COMPLETE, IDEMPOTENT DATABASE SETUP — paste into the Supabase SQL Editor
-- =============================================================================
--
-- This file is generated by scripts/build_apply_all.js from supabase/migrations.
-- Do not edit by hand. Run it once on an empty project, or re-run it any time
-- to reconcile an existing one (every statement is idempotent).
--
-- Contents (in order):
${files.map((f, i) => `--   ${String(i + 1).padStart(2, '0')}. ${f}`).join('\n')}
--
-- Prerequisites provided by Supabase itself: schema auth, schema storage,
-- roles anon / authenticated / service_role, extensions pgcrypto / citext / pg_trgm.
-- =============================================================================

`;

const parts = files.map((f) => {
  const sql = fs.readFileSync(path.join(migrationsDir, f), 'utf8').trimEnd();
  return `-- ###########################################################################\n-- ## ${f}\n-- ###########################################################################\n\n${sql}\n`;
});

const out = header + parts.join('\n');

const targets = [
  path.resolve('supabase', 'APPLY_ALL.sql'),
  path.resolve('supabase', 'master_schema.sql'),
  path.resolve('supabase', 'full_schema.sql'),
  path.resolve('public', 'szmc_master_schema.sql'),
  path.resolve('public', 'szmc_full_schema.sql'),
];

for (const t of targets) {
  fs.mkdirSync(path.dirname(t), { recursive: true });
  fs.writeFileSync(t, out);
}

console.log(
  `Built ${targets.length} files from ${files.length} migrations (${(out.length / 1024).toFixed(1)} KB).`
);
