BEGIN;

SET search_path = public, extensions;

-- -----------------------------------------------------------------------------
-- 1. HARDEN EXISTING public.connections (REUSE — NO DUPLICATE FRIENDSHIP TABLE)
-- -----------------------------------------------------------------------------
DO $$
BEGIN
  IF to_regclass('public.connections') IS NOT NULL THEN
    -- Prevent self-connections
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'chk_connections_no_self') THEN
      DELETE FROM public.connections WHERE user_id = friend_id;
      ALTER TABLE public.connections
        ADD CONSTRAINT chk_connections_no_self CHECK (user_id <> friend_id);
    END IF;
  END IF;
END $$;

CREATE INDEX IF NOT EXISTS idx_connections_friend_status
  ON public.connections (friend_id, status, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_connections_user_status
  ON public.connections (user_id, status, created_at DESC);

ALTER TABLE public.connections ENABLE ROW LEVEL SECURITY;

REVOKE INSERT, UPDATE, DELETE ON public.connections FROM anon;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.connections TO authenticated;

DROP POLICY IF EXISTS "connections_all_access" ON public.connections;
DROP POLICY IF EXISTS "connections_select_own" ON public.connections;
DROP POLICY IF EXISTS "connections_insert_own" ON public.connections;
DROP POLICY IF EXISTS "connections_update_recipient" ON public.connections;
DROP POLICY IF EXISTS "connections_delete_participant" ON public.connections;

CREATE POLICY "connections_select_own"
  ON public.connections FOR SELECT TO authenticated
  USING (
    user_id = public.current_alumni_profile_id()
    OR friend_id = public.current_alumni_profile_id()
    OR status = 'accepted'
    OR public.is_admin_or_mod()
  );

-- Only the requester can initiate a pending connection request (cannot self-accept someone else)
CREATE POLICY "connections_insert_own"
  ON public.connections FOR INSERT TO authenticated
  WITH CHECK (
    user_id = public.current_alumni_profile_id()
    AND user_id <> friend_id
    AND status = 'pending'
  );

-- Only the recipient (or admin) can accept / decline a pending request
CREATE POLICY "connections_update_recipient"
  ON public.connections FOR UPDATE TO authenticated
  USING (
    friend_id = public.current_alumni_profile_id()
    OR public.is_admin_or_mod()
  )
  WITH CHECK (
    (friend_id = public.current_alumni_profile_id() AND status IN ('accepted', 'rejected', 'blocked'))
    OR public.is_admin_or_mod()
  );

-- Either participant (or admin) can cancel a request or remove an existing connection
CREATE POLICY "connections_delete_participant"
  ON public.connections FOR DELETE TO authenticated
  USING (
    user_id = public.current_alumni_profile_id()
    OR friend_id = public.current_alumni_profile_id()
    OR public.is_admin_or_mod()
  );

