-- -----------------------------------------------------------------------------
-- 5. STANDARDIZE MULTI-REACTIONS ON public.post_likes
-- -----------------------------------------------------------------------------
DO $$
BEGIN
  IF to_regclass('public.post_likes') IS NOT NULL THEN
    ALTER TABLE public.post_likes
      ADD COLUMN IF NOT EXISTS reaction TEXT NOT NULL DEFAULT 'like';

    UPDATE public.post_likes
    SET reaction = 'like'
    WHERE reaction IS NULL OR reaction NOT IN ('like', 'love', 'care', 'haha', 'wow', 'sad', 'angry');

    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'chk_post_likes_reaction') THEN
      ALTER TABLE public.post_likes
        ADD CONSTRAINT chk_post_likes_reaction
        CHECK (reaction IN ('like', 'love', 'care', 'haha', 'wow', 'sad', 'angry'));
    END IF;
  END IF;
END $$;

CREATE UNIQUE INDEX IF NOT EXISTS uq_post_likes_post_user
  ON public.post_likes (post_id, user_id);

-- -----------------------------------------------------------------------------
-- 6. HARDEN public.saved_posts (PRIVATE PER USER, NO ANON WRITES)
