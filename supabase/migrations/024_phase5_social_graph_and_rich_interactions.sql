  );

-- -----------------------------------------------------------------------------
-- 3. EXTEND public.posts WITH REPOSTS & MENTIONS (ADDITIVE)
-- -----------------------------------------------------------------------------
DO $$
BEGIN
  IF to_regclass('public.posts') IS NOT NULL THEN
    ALTER TABLE public.posts
      ADD COLUMN IF NOT EXISTS repost_of_id BIGINT NULL REFERENCES public.posts(id) ON DELETE SET NULL;

    ALTER TABLE public.posts
      ADD COLUMN IF NOT EXISTS repost_count INT NOT NULL DEFAULT 0;

    ALTER TABLE public.posts
      ADD COLUMN IF NOT EXISTS mentioned_user_ids BIGINT[] NOT NULL DEFAULT '{}';
  END IF;
END $$;

CREATE INDEX IF NOT EXISTS idx_posts_repost_of
  ON public.posts (repost_of_id)
  WHERE repost_of_id IS NOT NULL;

CREATE OR REPLACE FUNCTION public.sync_post_repost_count()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_catalog
AS $$
BEGIN
  IF TG_OP = 'INSERT' AND NEW.repost_of_id IS NOT NULL AND COALESCE(NEW.is_deleted, FALSE) = FALSE THEN
    UPDATE public.posts SET repost_count = repost_count + 1 WHERE id = NEW.repost_of_id;
  ELSIF TG_OP = 'DELETE' AND OLD.repost_of_id IS NOT NULL AND COALESCE(OLD.is_deleted, FALSE) = FALSE THEN
    UPDATE public.posts SET repost_count = GREATEST(0, repost_count - 1) WHERE id = OLD.repost_of_id;
  ELSIF TG_OP = 'UPDATE' AND OLD.repost_of_id IS NOT NULL AND COALESCE(OLD.is_deleted, FALSE) = FALSE AND COALESCE(NEW.is_deleted, FALSE) = TRUE THEN
    UPDATE public.posts SET repost_count = GREATEST(0, repost_count - 1) WHERE id = OLD.repost_of_id;
  END IF;
  RETURN COALESCE(NEW, OLD);
END;
$$;

DROP TRIGGER IF EXISTS trg_sync_post_repost_count ON public.posts;
CREATE TRIGGER trg_sync_post_repost_count
  AFTER INSERT OR UPDATE OR DELETE ON public.posts
  FOR EACH ROW
  EXECUTE FUNCTION public.sync_post_repost_count();

