-- Non-destructively adds & hardens:
--   1. Hardens existing public.connections (self-connect guard, indexes, strict RLS).
--   2. Creates public.user_follows for asymmetric alumni following (strict RLS).
--   3. Extends public.posts with repost_of_id, repost_count, mentioned_user_ids
--      plus trigger maintaining repost_count automatically.
--   4. Extends public.post_comments with parent_comment_id and mentioned_user_ids
--      for true persisted nested comment threads.
--   5. Standardizes public.post_likes.reaction for 7 multi-reactions + unique key.
--   6. Hardens public.saved_posts RLS so bookmarks are strictly private per owner.
--   7. Links public.community_polls to public.posts via post_id for inline feed polls.
--   8. Refreshes public.get_quad_feed(...) to incorporate user_follows, reposts,
--      multi-reaction summaries, and nested comment parentCommentId.
