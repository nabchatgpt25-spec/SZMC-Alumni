-- Notification types enum
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'notification_type') THEN
    CREATE TYPE public.notification_type AS ENUM (
      'like',
      'comment',
      'post',
      'system',
      'blood',
      'verification',
      'mentorship',
      'career'
    );
  END IF;
END $$;

-- Notifications table
CREATE TABLE IF NOT EXISTS public.notifications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  recipient_id BIGINT NOT NULL REFERENCES public.alumni_profiles(id) ON DELETE CASCADE,
  actor_id BIGINT NULL REFERENCES public.alumni_profiles(id) ON DELETE SET NULL,
  type public.notification_type NOT NULL DEFAULT 'system',
  title TEXT NOT NULL CHECK (char_length(trim(title)) BETWEEN 1 AND 250),
  message TEXT NOT NULL CHECK (char_length(trim(message)) BETWEEN 1 AND 1500),
  unread BOOLEAN NOT NULL DEFAULT TRUE,
  target_route TEXT NULL,
  post_id BIGINT NULL REFERENCES public.posts(id) ON DELETE CASCADE,
  blood_request_id UUID NULL REFERENCES public.blood_requests(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Indexes for lightning fast lookups & counts
CREATE INDEX IF NOT EXISTS idx_notifications_recipient_cursor
  ON public.notifications (recipient_id, created_at DESC, id DESC);

CREATE INDEX IF NOT EXISTS idx_notifications_recipient_unread
  ON public.notifications (recipient_id, created_at DESC)
  WHERE unread = TRUE;

CREATE INDEX IF NOT EXISTS idx_notifications_actor
  ON public.notifications (actor_id)
  WHERE actor_id IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_notifications_post_id
  ON public.notifications (post_id)
  WHERE post_id IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_notifications_blood_request_id
  ON public.notifications (blood_request_id)
  WHERE blood_request_id IS NOT NULL;
