-- Bidirectional block check helper
CREATE OR REPLACE FUNCTION public.is_blocked_between(p_a BIGINT, p_b BIGINT)
RETURNS BOOLEAN
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public, pg_catalog
AS $$
  SELECT CASE
    WHEN p_a IS NULL OR p_b IS NULL OR p_a = p_b THEN FALSE
    ELSE EXISTS (
      SELECT 1
      FROM public.user_blocks ub
      WHERE (ub.blocker_id = p_a AND ub.blocked_id = p_b)
         OR (ub.blocker_id = p_b AND ub.blocked_id = p_a)
    )
  END;
$$;

GRANT EXECUTE ON FUNCTION public.is_blocked_between(BIGINT, BIGINT) TO authenticated, service_role;

-- Sever existing connections and follows in both directions when a user blocks another
CREATE OR REPLACE FUNCTION public.cleanup_social_on_block()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_catalog
AS $$
BEGIN
  IF to_regclass('public.connections') IS NOT NULL THEN
    DELETE FROM public.connections
    WHERE (user_id = NEW.blocker_id AND friend_id = NEW.blocked_id)
       OR (user_id = NEW.blocked_id AND friend_id = NEW.blocker_id);
  END IF;

  IF to_regclass('public.user_follows') IS NOT NULL THEN
    DELETE FROM public.user_follows
    WHERE (follower_id = NEW.blocker_id AND following_id = NEW.blocked_id)
       OR (follower_id = NEW.blocked_id AND following_id = NEW.blocker_id);
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_cleanup_social_on_block ON public.user_blocks;
CREATE TRIGGER trg_cleanup_social_on_block
  AFTER INSERT ON public.user_blocks
  FOR EACH ROW
  EXECUTE FUNCTION public.cleanup_social_on_block();

