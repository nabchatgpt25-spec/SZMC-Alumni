-- 4. Function: get_feed
CREATE OR REPLACE FUNCTION public.get_feed(
  p_user_id BIGINT DEFAULT NULL,
  p_limit INT DEFAULT 25,
  p_offset INT DEFAULT 0
)
RETURNS TABLE (
  id BIGINT,
  user_id BIGINT,
  author_id BIGINT,
  full_name TEXT,
  avatar_url TEXT,
  batch_year INT,
  verified BOOLEAN,
  profession TEXT,
  institution TEXT,
  content TEXT,
  category TEXT,
  images JSONB,
  videos JSONB,
  layout_template TEXT,
  linked_url TEXT,
  link_metadata JSONB,
  likes_count INT,
  comments_count INT,
  is_pinned BOOLEAN,
  is_edited BOOLEAN,
  created_at TIMESTAMPTZ,
  liked_by_me BOOLEAN,
  saved_by_me BOOLEAN,
  is_batchmate BOOLEAN,
  is_friend BOOLEAN,
  comments JSONB
)
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  v_caller_id BIGINT := p_user_id;
  v_my_batch INT := NULL;
BEGIN
  -- Infer profile id from auth.uid() if not provided
  IF v_caller_id IS NULL AND auth.uid() IS NOT NULL THEN
    SELECT p.id INTO v_caller_id
    FROM public.alumni_profiles p
    WHERE p.auth_user_id = auth.uid()
    LIMIT 1;
  END IF;

  -- Get current user's batch year
  IF v_caller_id IS NOT NULL THEN
    SELECT p.batch_year INTO v_my_batch
    FROM public.alumni_profiles p
    WHERE p.id = v_caller_id
    LIMIT 1;
  END IF;

  RETURN QUERY
  WITH my_friends AS (
    SELECT c.friend_id AS fid
    FROM public.connections c
    WHERE c.user_id = v_caller_id AND c.status = 'accepted'
    UNION
    SELECT c.user_id AS fid
    FROM public.connections c
    WHERE c.friend_id = v_caller_id AND c.status = 'accepted'
  ),
  ranked_posts AS (
    SELECT
      po.id AS r_id,
      po.author_id AS r_author_id,
      COALESCE(ap.full_name, 'SZMC Alumnus')::TEXT AS r_full_name,
      COALESCE(ap.avatar_url, '/assets/aistudio/images__1__2778177d.png')::TEXT AS r_avatar_url,
      ap.batch_year AS r_batch_year,
      (ap.verification_status = 'verified') AS r_verified,
      COALESCE(ap.profession, 'Doctor / Medical Professional')::TEXT AS r_profession,
      ap.institution::TEXT AS r_institution,
      po.content::TEXT AS r_content,
      COALESCE(po.category, 'General Update')::TEXT AS r_category,
      CASE
        WHEN jsonb_typeof(to_jsonb(po.images)) = 'array' THEN to_jsonb(po.images)
        ELSE '[]'::jsonb
      END AS r_images,
      CASE
        WHEN jsonb_typeof(to_jsonb(po.videos)) = 'array' THEN to_jsonb(po.videos)
        ELSE '[]'::jsonb
      END AS r_videos,
      COALESCE(po.layout_template, po.link_metadata->>'layout_template', 'grid')::TEXT AS r_layout_template,
      po.linked_url::TEXT AS r_linked_url,
      COALESCE(po.link_metadata, '{}'::jsonb) AS r_link_metadata,
      COALESCE(po.likes_count, 0)::INT AS r_likes_count,
      COALESCE(po.comments_count, 0)::INT AS r_comments_count,
      COALESCE(po.is_pinned, FALSE) AS r_is_pinned,
      COALESCE(po.is_edited, FALSE) AS r_is_edited,
      po.created_at AS r_created_at,
      EXISTS (
        SELECT 1 FROM public.post_likes pl
        WHERE pl.post_id = po.id AND pl.user_id = v_caller_id
      ) AS r_liked_by_me,
      EXISTS (
        SELECT 1 FROM public.saved_posts sp
        WHERE sp.post_id = po.id AND sp.user_id = v_caller_id
      ) AS r_saved_by_me,
      (
        v_my_batch IS NOT NULL AND
        ap.batch_year IS NOT NULL AND
        ap.batch_year = v_my_batch AND
        ap.id != v_caller_id
      ) AS r_is_batchmate,
      (
        ap.id IN (SELECT fid FROM my_friends)
      ) AS r_is_friend,
      COALESCE(
        (
          SELECT jsonb_agg(
            jsonb_build_object(
              'id', pc.id,
              'postId', pc.post_id,
              'userId', COALESCE(pc.user_id, pc.author_id),
              'fullName', COALESCE(cap.full_name, 'SZMC Alumnus'),
              'avatarUrl', COALESCE(cap.avatar_url, '/assets/aistudio/images__1__2778177d.png'),
              'content', pc.content,
              'likesCount', COALESCE(pc.likes_count, 0),
              'createdAt', pc.created_at
            )
            ORDER BY pc.created_at ASC
          )
          FROM public.post_comments pc
          LEFT JOIN public.alumni_profiles cap ON cap.id = COALESCE(pc.user_id, pc.author_id)
          WHERE pc.post_id = po.id AND COALESCE(pc.is_deleted, false) = false
        ),
        '[]'::jsonb
      ) AS r_comments
    FROM public.posts po
    LEFT JOIN public.alumni_profiles ap ON ap.id = po.author_id
    WHERE COALESCE(po.is_deleted, FALSE) = FALSE
    ORDER BY
      -- 1. Institutional Pinned posts
      COALESCE(po.is_pinned, FALSE) DESC,
      -- 2. Rank batchmates first
      (CASE WHEN v_my_batch IS NOT NULL AND ap.batch_year = v_my_batch AND ap.id != v_caller_id THEN 1 ELSE 0 END) DESC,
      -- 3. Then accepted connections
      (CASE WHEN ap.id IN (SELECT fid FROM my_friends) THEN 1 ELSE 0 END) DESC,
      -- 4. Then likes/reactions/comments + recency
      (COALESCE(po.likes_count, 0) * 2 + COALESCE(po.comments_count, 0) * 3) DESC,
      po.created_at DESC
    LIMIT p_limit
    OFFSET p_offset
  )
  SELECT
    r_id,
    r_author_id,
    r_author_id,
    r_full_name,
    r_avatar_url,
    r_batch_year,
    r_verified,
    r_profession,
    r_institution,
    r_content,
    r_category,
    r_images,
    r_videos,
    r_layout_template,
    r_linked_url,
    r_link_metadata,
    r_likes_count,
    r_comments_count,
    r_is_pinned,
    r_is_edited,
    r_created_at,
    r_liked_by_me,
    r_saved_by_me,
    r_is_batchmate,
    r_is_friend,
    r_comments
  FROM ranked_posts;
END;
$$;

GRANT EXECUTE ON FUNCTION public.get_feed(BIGINT, INT, INT) TO anon, authenticated, service_role;

-- 5. Function: unread_notifications
CREATE OR REPLACE FUNCTION public.unread_notifications(
  p_user_id BIGINT DEFAULT NULL
)
RETURNS TABLE (
  id BIGINT,
  recipient_id BIGINT,
  actor_id BIGINT,
  actor_name TEXT,
  actor_avatar TEXT,
  type TEXT,
  title TEXT,
  message TEXT,
  unread BOOLEAN,
  target_route TEXT,
  post_id BIGINT,
  blood_request_id UUID,
  created_at TIMESTAMPTZ
)
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  v_caller_id BIGINT := p_user_id;
BEGIN
  IF v_caller_id IS NULL AND auth.uid() IS NOT NULL THEN
    SELECT p.id INTO v_caller_id
    FROM public.alumni_profiles p
    WHERE p.auth_user_id = auth.uid()
    LIMIT 1;
  END IF;

  RETURN QUERY
  SELECT
    n.id,
    n.recipient_id,
    n.actor_id,
    COALESCE(ap.full_name, 'SZMC Alumnus')::TEXT AS actor_name,
    COALESCE(ap.avatar_url, '/assets/aistudio/images__1__2778177d.png')::TEXT AS actor_avatar,
    n.type::TEXT,
    n.title,
    n.message,
    n.unread,
    n.target_route,
    n.post_id,
    n.blood_request_id,
    n.created_at
  FROM public.notifications n
  LEFT JOIN public.alumni_profiles ap ON ap.id = n.actor_id
  WHERE n.recipient_id = v_caller_id
    AND n.unread = TRUE
  ORDER BY n.created_at DESC;
END;
$$;

GRANT EXECUTE ON FUNCTION public.unread_notifications(BIGINT) TO anon, authenticated, service_role;
