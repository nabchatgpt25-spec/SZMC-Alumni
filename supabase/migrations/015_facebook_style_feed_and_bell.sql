-- 1. Connections table for alumni networking
CREATE TABLE IF NOT EXISTS public.connections (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES public.alumni_profiles(id) ON DELETE CASCADE,
  friend_id BIGINT NOT NULL REFERENCES public.alumni_profiles(id) ON DELETE CASCADE,
  status TEXT NOT NULL DEFAULT 'accepted' CHECK (status IN ('pending', 'accepted', 'rejected', 'blocked')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT unique_user_friend UNIQUE (user_id, friend_id)
);

CREATE INDEX IF NOT EXISTS idx_connections_user_friend ON public.connections (user_id, friend_id, status);

GRANT SELECT, INSERT, UPDATE, DELETE ON public.connections TO anon, authenticated, service_role;

ALTER TABLE public.connections ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "connections_all_access" ON public.connections;
CREATE POLICY "connections_all_access" ON public.connections FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

