      SELECT 1 FROM pg_constraint WHERE conname = 'chk_posts_post_kind'
    ) THEN
      ALTER TABLE public.posts
        ADD CONSTRAINT chk_posts_post_kind
        CHECK (post_kind IN ('discussion', 'announcement', 'event', 'memory', 'poll'));
    END IF;

    IF NOT EXISTS (
      SELECT 1 FROM pg_constraint WHERE conname = 'chk_posts_single_space'
    ) THEN
      ALTER TABLE public.posts
        ADD CONSTRAINT chk_posts_single_space
        CHECK (NOT (batch_lounge_year IS NOT NULL AND official_page_id IS NOT NULL));
    END IF;
  END IF;
END $$;

