-- Synchronize followers_count on public.official_pages
CREATE OR REPLACE FUNCTION public.sync_official_page_followers_count()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_catalog
AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    UPDATE public.official_pages
    SET followers_count = followers_count + 1, updated_at = now()
    WHERE id = NEW.page_id;
    RETURN NEW;
  ELSIF TG_OP = 'DELETE' THEN
    UPDATE public.official_pages
    SET followers_count = GREATEST(0, followers_count - 1), updated_at = now()
    WHERE id = OLD.page_id;
    RETURN OLD;
  END IF;
  RETURN NULL;
END;
$$;

DROP TRIGGER IF EXISTS trg_sync_official_page_followers_count ON public.official_page_followers;
CREATE TRIGGER trg_sync_official_page_followers_count
  AFTER INSERT OR DELETE ON public.official_page_followers
  FOR EACH ROW
  EXECUTE FUNCTION public.sync_official_page_followers_count();

