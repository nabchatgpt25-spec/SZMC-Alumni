ALTER TABLE public.official_page_followers REPLICA IDENTITY FULL;
ALTER TABLE public.community_polls REPLICA IDENTITY FULL;
ALTER TABLE public.community_poll_votes REPLICA IDENTITY FULL;

DO $$
DECLARE
  v_tbl TEXT;
BEGIN
  IF EXISTS (SELECT 1 FROM pg_publication WHERE pubname = 'supabase_realtime') THEN
    FOREACH v_tbl IN ARRAY ARRAY[
      'batch_lounges',
      'official_pages',
      'official_page_followers',
      'community_polls',
      'community_poll_votes'
    ] LOOP
      IF NOT EXISTS (
        SELECT 1
        FROM pg_publication_tables
        WHERE pubname = 'supabase_realtime'
          AND schemaname = 'public'
          AND tablename = v_tbl
      ) THEN
        EXECUTE format('ALTER PUBLICATION supabase_realtime ADD TABLE public.%I', v_tbl);
      END IF;
    END LOOP;
  END IF;
END $$;

COMMIT;
