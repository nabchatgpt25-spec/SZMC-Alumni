-- -----------------------------------------------------------------------------
-- 7. AUTHORIZATION HELPERS & SERVER-SIDE PUBLISHING GUARD
-- -----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.can_publish_as_official_page(p_page_id BIGINT)
RETURNS BOOLEAN
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public, pg_catalog
AS $$
  SELECT
    public.is_admin()
    OR EXISTS (
      SELECT 1
      FROM public.official_page_roles r
      JOIN public.alumni_profiles ap ON ap.id = r.profile_id
      WHERE r.page_id = p_page_id
        AND ap.auth_user_id = auth.uid()
        AND r.role IN ('admin', 'editor')
    );
$$;

CREATE OR REPLACE FUNCTION public.is_batch_lounge_moderator(p_batch_year SMALLINT)
RETURNS BOOLEAN
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public, pg_catalog
AS $$
  SELECT
    public.is_admin_or_mod()
    OR EXISTS (
      SELECT 1
      FROM public.batch_lounge_moderators m
      JOIN public.alumni_profiles ap ON ap.id = m.profile_id
      WHERE m.batch_year = p_batch_year
        AND ap.auth_user_id = auth.uid()
    )
    OR EXISTS (
      SELECT 1
      FROM public.batches b
      JOIN public.alumni_profiles ap ON ap.id = b.representative_profile_id
      WHERE b.batch_year = p_batch_year
        AND ap.auth_user_id = auth.uid()
    );
$$;

GRANT EXECUTE ON FUNCTION public.can_publish_as_official_page(BIGINT) TO authenticated, service_role;
GRANT EXECUTE ON FUNCTION public.is_batch_lounge_moderator(SMALLINT) TO authenticated, service_role;

-- Enforce Official Page & Batch Lounge publishing rules at database trigger layer
CREATE OR REPLACE FUNCTION public.guard_community_space_post()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_catalog
AS $$
DECLARE
  v_jwt_role TEXT := COALESCE(current_setting('request.jwt.claim.role', true), '');
  v_my_batch SMALLINT;
BEGIN
  -- Allow migrations / service_role server operations
  IF auth.uid() IS NULL OR v_jwt_role = 'service_role' THEN
    RETURN NEW;
  END IF;

  -- Official Page publishing check: strictly Page Admin/Editor or Portal Admin/Super Admin
  IF NEW.official_page_id IS NOT NULL THEN
    IF NOT public.can_publish_as_official_page(NEW.official_page_id) THEN
      RAISE EXCEPTION 'Forbidden: Only authorized administrators or editors of this Official Page can publish on its behalf.';
    END IF;
  END IF;

  -- Batch Lounge posting check: member of that batch OR batch moderator OR portal admin/mod
  IF NEW.batch_lounge_year IS NOT NULL THEN
    IF NOT public.is_batch_lounge_moderator(NEW.batch_lounge_year) THEN
      SELECT batch_year INTO v_my_batch
      FROM public.alumni_profiles
      WHERE auth_user_id = auth.uid()
      LIMIT 1;

      IF v_my_batch IS DISTINCT FROM NEW.batch_lounge_year THEN
        RAISE EXCEPTION 'Forbidden: Only members or moderators of Batch % can post inside this Batch Lounge.', NEW.batch_lounge_year;
      END IF;
    END IF;

    -- Only Batch Moderators or Admins may pin a Batch Lounge post
    IF NEW.is_pinned IS TRUE AND (TG_OP = 'INSERT' OR COALESCE(OLD.is_pinned, FALSE) = FALSE) THEN
      IF NOT public.is_batch_lounge_moderator(NEW.batch_lounge_year) THEN
        RAISE EXCEPTION 'Forbidden: Only Batch Lounge moderators or administrators can pin announcements.';
      END IF;
    END IF;
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_guard_community_space_post ON public.posts;
CREATE TRIGGER trg_guard_community_space_post
  BEFORE INSERT OR UPDATE ON public.posts
  FOR EACH ROW
  EXECUTE FUNCTION public.guard_community_space_post();

-- Synchronize posts_count on batch_lounges and official_pages
CREATE OR REPLACE FUNCTION public.sync_space_posts_count()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_catalog
AS $$
BEGIN
  IF TG_OP = 'INSERT' AND COALESCE(NEW.is_deleted, FALSE) = FALSE THEN
    IF NEW.batch_lounge_year IS NOT NULL THEN
      UPDATE public.batch_lounges SET posts_count = posts_count + 1, updated_at = now()
      WHERE batch_year = NEW.batch_lounge_year;
    END IF;
    IF NEW.official_page_id IS NOT NULL THEN
      UPDATE public.official_pages SET posts_count = posts_count + 1, updated_at = now()
      WHERE id = NEW.official_page_id;
    END IF;
  ELSIF TG_OP = 'UPDATE' THEN
    IF COALESCE(OLD.is_deleted, FALSE) = FALSE AND COALESCE(NEW.is_deleted, FALSE) = TRUE THEN
      IF OLD.batch_lounge_year IS NOT NULL THEN
        UPDATE public.batch_lounges SET posts_count = GREATEST(0, posts_count - 1), updated_at = now()
        WHERE batch_year = OLD.batch_lounge_year;
      END IF;
      IF OLD.official_page_id IS NOT NULL THEN
        UPDATE public.official_pages SET posts_count = GREATEST(0, posts_count - 1), updated_at = now()
        WHERE id = OLD.official_page_id;
      END IF;
    END IF;
  ELSIF TG_OP = 'DELETE' AND COALESCE(OLD.is_deleted, FALSE) = FALSE THEN
    IF OLD.batch_lounge_year IS NOT NULL THEN
      UPDATE public.batch_lounges SET posts_count = GREATEST(0, posts_count - 1), updated_at = now()
      WHERE batch_year = OLD.batch_lounge_year;
    END IF;
    IF OLD.official_page_id IS NOT NULL THEN
      UPDATE public.official_pages SET posts_count = GREATEST(0, posts_count - 1), updated_at = now()
      WHERE id = OLD.official_page_id;
    END IF;
  END IF;
  RETURN NULL;
END;
$$;

DROP TRIGGER IF EXISTS trg_sync_space_posts_count ON public.posts;
CREATE TRIGGER trg_sync_space_posts_count
  AFTER INSERT OR UPDATE OR DELETE ON public.posts
  FOR EACH ROW
  EXECUTE FUNCTION public.sync_space_posts_count();

