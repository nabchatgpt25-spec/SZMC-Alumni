-- -----------------------------------------------------------------------------
-- 1. HELPER: CURRENT ALUMNI PROFILE ID
-- -----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.current_alumni_profile_id()
RETURNS BIGINT
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public, pg_catalog
AS $$
  SELECT id
  FROM public.alumni_profiles
  WHERE auth_user_id = auth.uid()
  LIMIT 1;
$$;

