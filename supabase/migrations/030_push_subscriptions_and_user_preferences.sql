-- Migration 030: Cross-Device User Preferences & Web Push Subscriptions
-- Safe, idempotent migration for persisting SettingsView preferences and
-- PWA Web Push subscriptions in Supabase Postgres.
-- =============================================================================

ALTER TABLE public.alumni_profiles
  ADD COLUMN IF NOT EXISTS user_preferences jsonb NOT NULL DEFAULT '{}'::jsonb;

CREATE TABLE IF NOT EXISTS public.push_subscriptions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  profile_id bigint NOT NULL REFERENCES public.alumni_profiles(id) ON DELETE CASCADE,
  endpoint text NOT NULL,
  p256dh text NOT NULL,
  auth text NOT NULL,
  user_agent text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (profile_id, endpoint)
);

ALTER TABLE public.push_subscriptions ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Users manage own push subscriptions" ON public.push_subscriptions;
CREATE POLICY "Users manage own push subscriptions"
  ON public.push_subscriptions
  FOR ALL
  TO authenticated
  USING (
    EXISTS (
      SELECT 1 FROM public.alumni_profiles ap
      WHERE ap.id = push_subscriptions.profile_id
        AND ap.auth_user_id = auth.uid()
    )
  )
  WITH CHECK (
    EXISTS (
      SELECT 1 FROM public.alumni_profiles ap
      WHERE ap.id = push_subscriptions.profile_id
        AND ap.auth_user_id = auth.uid()
    )
  );

NOTIFY pgrst, 'reload schema';
